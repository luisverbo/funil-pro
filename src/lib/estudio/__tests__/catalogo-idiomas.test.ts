// ============================================================================
// Estúdio IA — catálogo (página + PDF) no idioma do atendimento.
// ============================================================================
import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { idiomaDoCatalogo, textosDoCatalogo, linkDoCatalogo, caminhoPdfIdioma, nomeDoPdf, tituloDoTema, sufixoIdioma } from '@/lib/estudio/catalogo-idiomas'
import { mensagemDeEscolha } from '@/lib/estudio/catalogo'
import { posesDoTexto } from '@/lib/estudio/ana/maquina'
import { IDIOMAS } from '@/lib/estudio/ana/textos'
import { montarPdfCatalogo, textoPdf, quebrarLinhas } from '@/lib/estudio/pdf-catalogo'

const ler = (p: string) => readFileSync(join(process.cwd(), p), 'utf8')

const tests: Record<string, () => void | Promise<void>> = {
  '?l= vira idioma; sem parâmetro é português': () => {
    assert.equal(idiomaDoCatalogo(undefined), 'pt-BR')
    assert.equal(idiomaDoCatalogo('es'), 'es'); assert.equal(idiomaDoCatalogo('es-AR'), 'es')
    assert.equal(idiomaDoCatalogo('EN'), 'en'); assert.equal(idiomaDoCatalogo('pt-pt'), 'pt-PT')
    assert.equal(idiomaDoCatalogo(['en']), 'en'); assert.equal(idiomaDoCatalogo('xx'), 'pt-BR')
  },
  'link que a Ana manda leva o idioma (pt-BR igual ao de antes)': () => {
    assert.equal(linkDoCatalogo('https://a', 'casual', 'pt-BR'), 'https://a/estudio/catalogo/casual')
    assert.equal(linkDoCatalogo('https://a', 'casual', 'es'), 'https://a/estudio/catalogo/casual?l=es')
    assert.equal(linkDoCatalogo('https://a', null, 'en'), 'https://a/estudio/catalogo?l=en')
    assert.equal(sufixoIdioma('pt-BR'), ''); assert.equal(sufixoIdioma('en'), '?l=en')
  },
  'todos os textos existem nos 4 idiomas, e não ficam em português no es/en': () => {
    for (const i of IDIOMAS) {
      const t = textosDoCatalogo(i)
      for (const [k, v] of Object.entries(t)) assert.ok(typeof v === 'function' || String(v).trim(), `${i}.${k} vazio`)
    }
    const es = textosDoCatalogo('es'), en = textosDoCatalogo('en')
    assert.match(es.titulo, /Elige/); assert.match(en.titulo, /Choose/)
    assert.match(es.rodape, /generadas por IA/); assert.match(en.rodape, /generated by AI/)
    assert.doesNotMatch(en.tocar + en.preparando + en.escolherWa + en.pdfInstrucao, /[ãçõ]|você|Toque/)
  },
  'mensagem para o WhatsApp no idioma — e a Ana entende os números em qualquer um': () => {
    assert.equal(mensagemDeEscolha(['12', '3'], 'Birthday Photoshoot', textosDoCatalogo('en').querer), 'I want poses 03, 12 (Birthday Photoshoot)')
    assert.equal(mensagemDeEscolha(['7'], undefined, textosDoCatalogo('es').querer), 'Quiero la pose 07')
    assert.equal(mensagemDeEscolha(['7']), 'Quero a pose 07')
    assert.deepEqual(posesDoTexto('I want poses 03, 12 (Birthday Photoshoot)'), ['03', '12'])
    assert.deepEqual(posesDoTexto('Quiero las poses 05, 18'), ['05', '18'])
  },
  'nome do tema traduzido; tema novo sem tradução usa o nome cadastrado': () => {
    assert.equal(tituloDoTema('aniversario', 'Ensaio de Aniversário', 'pt-BR'), 'Ensaio de Aniversário')
    assert.equal(tituloDoTema('aniversario', 'Ensaio de Aniversário', 'es'), 'Sesión de cumpleaños')
    assert.equal(tituloDoTema('aniversario', 'Ensaio de Aniversário', 'en'), 'Birthday Photoshoot')
    assert.equal(tituloDoTema('praia', 'Ensaio na Praia', 'en'), 'Ensaio na Praia')
  },
  'PDF por idioma em caminho próprio e nome do arquivo traduzido': () => {
    assert.equal(caminhoPdfIdioma('casual', 'es'), 'casual/catalogo-casual-es.pdf')
    assert.equal(caminhoPdfIdioma('casual', 'en'), 'casual/catalogo-casual-en.pdf')
    assert.equal(nomeDoPdf('Birthday', 'en'), 'Catalog Birthday.pdf')
    assert.equal(nomeDoPdf('Cumpleaños', 'es'), 'Catálogo Cumpleaños.pdf')
  },
  'PDF válido: cabeçalho, páginas de 4 poses, xref e texto com acento': () => {
    const jpeg = { bytes: new Uint8Array([0xff, 0xd8, 0xff, 0xd9]), largura: 4, altura: 5 }
    const poses = Array.from({ length: 9 }, (_, i) => ({ numero: String(i + 1).padStart(2, '0'), foto: i === 2 ? null : jpeg }))
    const pdf = montarPdfCatalogo({ titulo: 'Catálogo · Sesión de cumpleaños', instrucao: 'Cada foto tiene un número 😉', rodape: 'Imágenes generadas por IA', poses })
    const s = Buffer.from(pdf).toString('latin1')
    assert.ok(s.startsWith('%PDF-1.4')); assert.ok(s.trimEnd().endsWith('%%EOF'))
    assert.match(s, /\/Count 3 /)
    assert.equal((s.match(/\/Subtype \/Image/g) ?? []).length, 8)
    assert.ok(s.includes('Sesi\xF3n de cumplea\xF1os'), 'acento em WinAnsi')
    assert.ok(!s.includes('😉'))
    // cada offset do xref aponta para "N 0 obj"
    const xref = Number(s.match(/startxref\n(\d+)/)![1])
    const linhas = s.slice(xref).split('\n').slice(3).filter(l => / n $/.test(l))
    linhas.forEach((l, i) => assert.ok(s.startsWith(`${i + 1} 0 obj`, Number(l.slice(0, 10))), `obj ${i + 1}`))
  },
  'texto do PDF escapa parênteses; linhas quebram': () => {
    assert.deepEqual(textoPdf('(a)'), [0x5c, 0x28, 0x61, 0x5c, 0x29])
    assert.ok(quebrarLinhas('palavra '.repeat(40), 10, 200).length > 1)
  },
  'Ana: link e PDF no idioma, nunca o PDF em português para es/en': () => {
    const ex = ler('src/lib/estudio/ana/executor.ts')
    assert.match(ex, /link: linkDoCatalogo\(APP_URL\(\), dados\.tema, idioma\)/)
    assert.match(ex, /if \(idioma === 'pt-BR' \|\| idioma === 'pt-PT'\) \{\s*const doPc/)
    assert.match(ex, /nomeDoPdf\(nomeDoTema\(a\.tema, idioma\), idioma\)/)
  },
  'páginas públicas usam os textos do idioma (sem texto fixo em português)': () => {
    const lista = ler('src/app/estudio/catalogo/page.tsx'), tema = ler('src/app/estudio/catalogo/[slug]/page.tsx'), grade = ler('src/app/estudio/catalogo/[slug]/grade-poses.tsx')
    for (const f of [lista, tema]) assert.match(f, /idiomaDoCatalogo\(\(await searchParams\)\.l\)/)
    assert.doesNotMatch(lista + tema + grade, /Escolha o seu ensaio|Toque no número|Copiar números|foto em breve|Todos os temas/)
  },
}

;(async () => {
  let passed = 0
  const nomes = Object.keys(tests)
  for (const nome of nomes) {
    try { await tests[nome](); passed++; console.log(`  ok   ${nome}`) }
    catch (e) { console.log(` FALHA ${nome}\n        → ${e instanceof Error ? e.message : String(e)}`) }
  }
  console.log(`\n${passed}/${nomes.length} testes passaram`)
  if (passed !== nomes.length) process.exit(1)
})()
